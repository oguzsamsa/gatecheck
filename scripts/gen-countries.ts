/**
 * Regenerates src/geo/countries.data.ts from CLDR via Intl.DisplayNames.
 *
 * The table is generated once and committed rather than built at runtime because CLDR
 * names drift between ICU releases (e.g. "Turkey" became "Türkiye"); matching must not
 * depend on which Node build happens to run the poller. Hand-maintained aliases live in
 * countries.ts, not here.
 *
 *   node scripts/gen-countries.ts
 */
import { writeFileSync } from 'node:fs';

// Codes CLDR knows that are not current ISO 3166-1 alpha-2 countries: deprecated codes,
// exceptional reservations, supranational groupings and pseudo-locales. XK (Kosovo) is
// user-assigned but universally used, so it stays.
const NOT_COUNTRIES = new Set(
  'AC AN BU CP CQ CS DD DG DY EA EU EZ FX HV IC NH QO RH SU TA TP UK UN VD XA XB YD YU ZR ZZ'.split(
    ' ',
  ),
);

const names = new Intl.DisplayNames('en', { type: 'region', fallback: 'none' });
const letters = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ';
const rows: string[] = [];
for (const a of letters) {
  for (const b of letters) {
    const code = a + b;
    const name = names.of(code);
    if (name && !NOT_COUNTRIES.has(code)) rows.push(`  ${code}: ${JSON.stringify(name)},`);
  }
}

const out = `// Generated by scripts/gen-countries.ts from CLDR (ICU ${process.versions.icu}). Do not edit.
export const COUNTRY_NAMES = {
${rows.join('\n')}
} as const;
`;
writeFileSync(new URL('../src/geo/countries.data.ts', import.meta.url), out);
console.log(`wrote ${rows.length} countries`);
