/**
 * Phase 3: for postings that passed the deterministic filter, ask a model what the text
 * says — fit, location wording, a first draft — and keep it honest with a mechanical
 * grounding check. The model never changes a verdict and nothing is ever sent anywhere:
 * drafts are files for the applicant to edit.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { and, desc, eq, inArray, isNull } from 'drizzle-orm';
import type { Db } from '../db/client.ts';
import {
  analysis,
  company,
  eligibility,
  locationClaim,
  posting,
  postingVersion,
} from '../db/schema.ts';
import { placeLabel } from '../domain/format.ts';
import type { Ats } from '../domain/types.ts';
import type { CountryCode } from '../geo/countries.ts';
import { foldPlaceText } from '../geo/text.ts';
import { matchesKeywords } from '../notify/digest.ts';
import type { BoardSource } from '../sources/types.ts';
import type { Analyzer } from './claude.ts';
import { checkGrounding } from './grounding.ts';
import { systemPrompt, userPrompt, type PostingForAnalysis } from './prompt.ts';
import type { AnalysisResult } from './schema.ts';

export interface AnalyzeDeps {
  db: Db;
  analyzer: Analyzer;
  sources: Record<Ats, BoardSource>;
  applicant: CountryCode;
  profile: string;
  titleKeywords: readonly string[];
  excludeTitleKeywords?: readonly string[];
  draftsDir: string | null;
  now?: () => Date;
}

export interface AnalyzeReport {
  analyzed: { postingId: number; title: string; fit: string; ungrounded: number }[];
  failed: { postingId: number; title: string; error: string }[];
  pending: number;
}

interface Candidate {
  postingId: number;
  ats: Ats;
  company: string;
  title: string;
  url: string;
  verdict: string;
  reason: string;
  hash: string;
  payload: unknown;
}

/** Open/unknown postings whose latest version has not been analysed yet; open ones first. */
function candidates(
  db: Db,
  keywords: readonly string[],
  exclude: readonly string[] = [],
): Candidate[] {
  const rows = db
    .select({
      postingId: posting.id,
      ats: company.ats,
      company: company.name,
      title: posting.title,
      url: posting.url,
      verdict: eligibility.verdict,
      reason: eligibility.reason,
      firstSeenAt: posting.firstSeenAt,
      analysedHash: analysis.contentHash,
    })
    .from(posting)
    .innerJoin(company, eq(company.id, posting.companyId))
    .innerJoin(eligibility, eq(eligibility.postingId, posting.id))
    .leftJoin(analysis, eq(analysis.postingId, posting.id))
    .where(and(isNull(posting.closedAt), inArray(eligibility.verdict, ['open', 'unknown'])))
    .all()
    .filter((r) => matchesKeywords(r.title, keywords, exclude));

  const out: Candidate[] = [];
  for (const r of rows) {
    const latest = db
      .select({ hash: postingVersion.contentHash, payload: postingVersion.payloadJson })
      .from(postingVersion)
      .where(eq(postingVersion.postingId, r.postingId))
      .orderBy(desc(postingVersion.id))
      .limit(1)
      .get();
    if (!latest || latest.hash === r.analysedHash) continue;
    out.push({ ...r, hash: latest.hash, payload: latest.payload });
  }
  const rank = (c: Candidate) => (c.verdict === 'open' ? 0 : 1);
  return out.sort((a, b) => rank(a) - rank(b) || b.postingId - a.postingId);
}

const slug = (s: string) => foldPlaceText(s).replace(/ /g, '-').slice(0, 60);

function renderDraft(c: Candidate, r: AnalysisResult, ungrounded: string[], model: string) {
  const list = (items: string[]) =>
    items.length ? items.map((i) => `- ${i}`).join('\n') : '- none';
  return `# ${c.title} — ${c.company}

${c.url}

Verdict: **${c.verdict}** (${c.reason})
Fit: **${r.fit}** — ${r.fit_summary}
${ungrounded.length ? `\n> ⚠️ Some claims are not backed by a verbatim profile quote — check before sending:\n${ungrounded.map((u) => `> - ${u}`).join('\n')}\n` : ''}
## Location wording
${list(r.location_signals.map((s) => `${s.reading}: "${s.quote}"`))}

## Requirements
${list(r.requirements.map((q) => `${q.status} — ${q.requirement}${q.profile_quote ? ` ("${q.profile_quote}")` : ''}`))}

## Claims used
${list(r.claims_used.map((c) => `${c.claim} ("${c.profile_quote}")`))}

## Claims left out
${list(r.claims_rejected.map((c) => `${c.claim} — ${c.reason}`))}

## Draft
${r.draft.trim()}

---
Generated by ${model}. Never sent automatically.
`;
}

export async function analyzePending(
  deps: AnalyzeDeps,
  options: { limit: number },
): Promise<AnalyzeReport> {
  const { db } = deps;
  const now = deps.now ?? (() => new Date());
  const pending = candidates(db, deps.titleKeywords, deps.excludeTitleKeywords);
  const report: AnalyzeReport = { analyzed: [], failed: [], pending: pending.length };
  const system = systemPrompt(deps.applicant, deps.profile);

  for (const c of pending.slice(0, options.limit)) {
    try {
      const source = deps.sources[c.ats];
      const input: PostingForAnalysis = {
        company: c.company,
        title: c.title,
        url: c.url,
        verdict: c.verdict,
        verdictReason: c.reason,
        locations: db
          .select()
          .from(locationClaim)
          .where(eq(locationClaim.postingId, c.postingId))
          .all()
          .map(placeLabel),
        text: source.text ? source.text(c.payload) : '',
      };
      const { result, model } = await deps.analyzer({ system, user: userPrompt(input) });
      const { ungrounded } = checkGrounding(result, deps.profile);

      let draftPath: string | null = null;
      if (deps.draftsDir) {
        mkdirSync(deps.draftsDir, { recursive: true });
        draftPath = join(deps.draftsDir, `${c.postingId}-${slug(c.company)}-${slug(c.title)}.md`);
        writeFileSync(draftPath, renderDraft(c, result, ungrounded, model));
      }

      const row = {
        contentHash: c.hash,
        model,
        analyzedAt: now(),
        fit: result.fit,
        summary: result.fit_summary,
        ungroundedCount: ungrounded.length,
        draftPath,
        resultJson: result,
      };
      db.insert(analysis)
        .values({ postingId: c.postingId, ...row })
        .onConflictDoUpdate({ target: analysis.postingId, set: row })
        .run();
      report.analyzed.push({
        postingId: c.postingId,
        title: c.title,
        fit: result.fit,
        ungrounded: ungrounded.length,
      });
    } catch (error) {
      report.failed.push({
        postingId: c.postingId,
        title: c.title,
        error: error instanceof Error ? error.message : String(error),
      });
    }
  }
  return report;
}

export function describeReport(report: AnalyzeReport): string {
  const lines = [
    ...report.analyzed.map(
      (r) =>
        `  ${r.fit.padEnd(8)} ${r.title}${r.ungrounded ? `  (${r.ungrounded} unbacked claims)` : ''}`,
    ),
    ...report.failed.map((f) => `  FAILED   ${f.title}: ${f.error}`),
  ];
  const left = report.pending - report.analyzed.length - report.failed.length;
  lines.push(
    `analysis: ${report.analyzed.length} done, ${report.failed.length} failed, ${left} still pending`,
  );
  return lines.join('\n');
}
